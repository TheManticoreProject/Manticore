//go:build ignore

// gen_tables writes tables_ibm.go from IBM's single-byte EBCDIC mappings as
// published in ICU's data repository
// (https://github.com/unicode-org/icu-data/tree/main/charset/data/ucm). Only
// round-trip entries ("|0") are used, so every table is a bijection between the
// 256 bytes and 256 code points.
//
//	go run gen_tables.go <directory holding the .ucm files>
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
)

// sources maps each code page this package carries a table for to its ICU
// mapping file. 037, 1047 and 1140 come from golang.org/x/text instead.
var sources = []struct {
	cp   int
	file string
}{
	{273, "ibm-273_P100-1999.ucm"}, {277, "ibm-277_P100-1999.ucm"}, {278, "ibm-278_P100-1999.ucm"},
	{280, "ibm-280_P100-1999.ucm"}, {284, "ibm-284_P100-1999.ucm"}, {285, "ibm-285_P100-1999.ucm"},
	{297, "ibm-297_P100-1999.ucm"}, {500, "ibm-500_P100-1999.ucm"}, {871, "ibm-871_P100-1999.ucm"},
	{1141, "ibm-1141_P100-1997.ucm"}, {1142, "ibm-1142_P100-1997.ucm"}, {1143, "ibm-1143_P100-1997.ucm"},
	{1144, "ibm-1144_P100-1997.ucm"}, {1145, "ibm-1145_P100-1997.ucm"}, {1146, "ibm-1146_P100-1997.ucm"},
	{1147, "ibm-1147_P100-1997.ucm"}, {1148, "ibm-1148_P100-1997.ucm"}, {1149, "ibm-1149_P100-1997.ucm"},
}

var entry = regexp.MustCompile(`^<U([0-9A-F]{4,6})>\s+\\x([0-9A-F]{2})\s+\|0`)

func main() {
	if len(os.Args) != 2 {
		log.Fatal("usage: go run gen_tables.go <ucm directory>")
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by gen_tables.go from ICU's IBM mapping files; DO NOT EDIT.\n\npackage ebcdic\n\n")
	out.WriteString("// ibmTables holds the byte-to-rune table of each IBM code page generated from\n// ICU's round-trip mappings.\nvar ibmTables = map[int]*[256]rune{\n")
	for _, s := range sources {
		table, err := load(filepath.Join(os.Args[1], s.file))
		if err != nil {
			log.Fatalf("%s: %v", s.file, err)
		}
		fmt.Fprintf(&out, "\t%d: { // %s\n", s.cp, s.file)
		for i, r := range table {
			if i%8 == 0 {
				out.WriteString("\t\t")
			}
			fmt.Fprintf(&out, "0x%04X,", r)
			if i%8 == 7 {
				out.WriteString("\n")
			} else {
				out.WriteString(" ")
			}
		}
		out.WriteString("\t},\n")
	}
	out.WriteString("}\n")
	src, err := format.Source(out.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("tables_ibm.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// load reads the round-trip entries of one .ucm file and checks they cover
// every byte exactly once with distinct code points.
func load(path string) ([256]rune, error) {
	var table [256]rune
	var seen [256]bool
	used := map[rune]bool{}
	f, err := os.Open(path)
	if err != nil {
		return table, err
	}
	defer f.Close()
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		m := entry.FindStringSubmatch(sc.Text())
		if m == nil {
			continue
		}
		u, _ := strconv.ParseUint(m[1], 16, 32)
		b, _ := strconv.ParseUint(m[2], 16, 8)
		if seen[b] || used[rune(u)] {
			return table, fmt.Errorf("byte 0x%02X or U+%04X mapped twice", b, u)
		}
		seen[b], used[rune(u)] = true, true
		table[b] = rune(u)
	}
	for b, ok := range seen {
		if !ok {
			return table, fmt.Errorf("byte 0x%02X has no round-trip mapping", b)
		}
	}
	return table, sc.Err()
}
