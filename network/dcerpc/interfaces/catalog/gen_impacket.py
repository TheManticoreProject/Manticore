#!/usr/bin/env python3
"""Generate data_impacket.go from impacket's endpoint-mapper tables.

It reads impacket's dcerpc/v5/epm.py and merges its two dictionaries:

  * KNOWN_UUIDS      keys are uuidtup_to_bin((uuid, version)) (16 UUID octets +
                     a 1-octet major and 1-octet minor); values are the
                     implementing image (e.g. "spoolsv.exe", "rpcss.dll").
  * KNOWN_PROTOCOLS  maps a hyphenated UUID string to "[MS-XXX]: Title".

Each KNOWN_UUIDS entry becomes an Interface with a UUID, version and Executable,
enriched with the Protocol/Title from KNOWN_PROTOCOLS when the UUID matches.
KNOWN_PROTOCOLS entries with no KNOWN_UUIDS counterpart are emitted at version
0.0 (the version used by the COM interfaces that make up most of that table),
carrying their Protocol/Title only. Entries already present in the curated
builtin table (data.go) are skipped so the hand-written metadata wins.

Usage:
    python3 gen_impacket.py [path-to-epm.py] > data_impacket.go
    gofmt -w data_impacket.go

If no path is given it downloads epm.py from the impacket master branch.
"""
import json
import os
import re
import struct
import sys
import urllib.request

EPM_URL = "https://raw.githubusercontent.com/fortra/impacket/master/impacket/dcerpc/v5/epm.py"
CURATED = os.path.join(os.path.dirname(__file__), "data.go")


def load_epm(path):
    if path:
        return open(path).read()
    return urllib.request.urlopen(EPM_URL, timeout=60).read().decode()


def decode_key(b):
    """Decode a KNOWN_UUIDS binary key into (uuid_lower, major, minor)."""
    d1 = struct.unpack("<I", b[0:4])[0]
    d2 = struct.unpack("<H", b[4:6])[0]
    d3 = struct.unpack("<H", b[6:8])[0]
    d4 = b[8:16]
    uuid = "%08x-%04x-%04x-%s-%s" % (d1, d2, d3, d4[:2].hex(), d4[2:].hex())
    return uuid, b[16], b[17]


def curated_keys():
    keys = set()
    for line in open(CURATED):
        m = re.search(r'mustGUID\("([0-9a-fA-F-]+)"\), Version: v\((\d+), (\d+)\)', line)
        if m:
            keys.add((m.group(1).lower(), int(m.group(2)), int(m.group(3))))
    return keys


def main():
    src = load_epm(sys.argv[1] if len(sys.argv) > 1 else None)
    KU = eval("{" + re.search(r"KNOWN_UUIDS = \{(.*?)\n\}", src, re.S).group(1) + "}")
    KP = eval("{" + re.search(r"KNOWN_PROTOCOLS = \{(.*?)\n\}", src, re.S).group(1) + "}")

    kp = {}
    for u, desc in KP.items():
        m = re.match(r"\[([\w-]+)\]:?\s*(.*)", desc)
        proto, title = (m.group(1), m.group(2)) if m else ("", desc)
        kp[u.lower()] = (proto, title.strip().rstrip(":").strip())

    curated = curated_keys()
    entries, seen, ku_uuids = [], set(), set()
    for k, image in KU.items():
        uuid, major, minor = decode_key(k)
        ku_uuids.add(uuid)
        key = (uuid, major, minor)
        if key in curated or key in seen:
            continue
        seen.add(key)
        proto, title = kp.get(uuid, ("", ""))
        entries.append((uuid, major, minor, image, proto, title))
    for uuid, (proto, title) in kp.items():
        if uuid in ku_uuids:
            continue
        key = (uuid, 0, 0)
        if key in curated or key in seen:
            continue
        seen.add(key)
        entries.append((uuid, 0, 0, "", proto, title))

    entries.sort(key=lambda e: (e[4], e[0], e[1], e[2]))

    out = [
        "package catalog\n",
        "// Code generated by gen_impacket.py from impacket dcerpc/v5/epm.py "
        "(KNOWN_UUIDS + KNOWN_PROTOCOLS). DO NOT EDIT.",
        "// KNOWN_UUIDS supplies the UUID, version and implementing image; KNOWN_PROTOCOLS",
        "// supplies the MS-* protocol document and title. Entries already in the curated",
        "// builtin table (data.go) are omitted so the richer hand-written metadata wins.\n",
        "var impacket = []Interface{",
    ]
    for uuid, major, minor, image, proto, title in entries:
        fields = ['UUID: mustGUID(%s)' % json.dumps(uuid), 'Version: v(%d, %d)' % (major, minor)]
        if title:
            fields.append("Title: %s" % json.dumps(title))
        if image:
            fields.append("Executable: %s" % json.dumps(image))
        if proto:
            fields.append("Protocol: %s" % json.dumps(proto))
        out.append("\t{" + ", ".join(fields) + "},")
    out.append("}")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
